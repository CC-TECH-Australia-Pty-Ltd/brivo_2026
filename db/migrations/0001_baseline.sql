-- 0001 Baseline: the four schemas, tenant helpers and the organisation table.
-- Plain PostgreSQL only, so it runs unchanged on Supabase and Amazon RDS.

-- Four schemas, none of them public. Supabase's automatic web API only exposes
-- "public", so nothing here can be reached through it.
CREATE SCHEMA platform;
CREATE SCHEMA content;
CREATE SCHEMA clinical;
CREATE SCHEMA media;

-- The API role can use the schemas and the tables migrations create, but never owns them.
DO $$
DECLARE s text;
BEGIN
  FOREACH s IN ARRAY ARRAY['platform', 'content', 'clinical', 'media'] LOOP
    EXECUTE format('GRANT USAGE ON SCHEMA %I TO brave_app', s);
    EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA %I
                    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO brave_app', s);
    EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA %I
                    GRANT USAGE, SELECT ON SEQUENCES TO brave_app', s);
    EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA %I
                    GRANT EXECUTE ON FUNCTIONS TO brave_app', s);
  END LOOP;
END $$;

-- The organisation for the current transaction, set by the API from the signed-in
-- user's token (brave.core.db.org_session). NULL when unset, so policies match nothing.
CREATE FUNCTION platform.current_org_id() RETURNS uuid
LANGUAGE sql STABLE AS $$
  SELECT nullif(current_setting('app.current_org_id', true), '')::uuid
$$;

-- Helper every migration uses for a new tenant table (it must have an org_id column):
--   SELECT platform.enable_tenant_rls('clinical.participant');
CREATE FUNCTION platform.enable_tenant_rls(target regclass) RETURNS void
LANGUAGE plpgsql AS $$
BEGIN
  EXECUTE format('ALTER TABLE %s ENABLE ROW LEVEL SECURITY', target);
  EXECUTE format('ALTER TABLE %s FORCE ROW LEVEL SECURITY', target);
  EXECUTE format(
    'CREATE POLICY tenant_isolation ON %s
       USING (org_id = platform.current_org_id())
       WITH CHECK (org_id = platform.current_org_id())', target);
END $$;
REVOKE EXECUTE ON FUNCTION platform.enable_tenant_rls(regclass) FROM PUBLIC, brave_app;

-- IDs are UUIDv7, generated by the application (brave.core.ids.new_id).
CREATE TABLE platform.organisation (
  id         uuid PRIMARY KEY,
  name       text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
